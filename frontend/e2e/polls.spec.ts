import { test, expect, chatId, user } from "./support";

test("anonymous poll creation, vote and retraction survive history reload", async ({ page, mockApi }) => {
  await mockApi.openChat();
  await page.getByRole("button", { name: "Создать опрос", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "Новый опрос" });
  await modal.getByLabel("Вопрос", { exact: true }).fill("Куда пойдём?");
  await modal.getByLabel("Вариант 1", { exact: true }).fill("В парк");
  await modal.getByLabel("Вариант 2", { exact: true }).fill("В кино");
  await modal.getByRole("button", { name: "Создать опрос", exact: true }).click();
  await expect(modal).toBeHidden();
  const card = page.getByRole("region", { name: "Опрос", exact: true });
  await expect(card).toContainText("Анонимно");
  await card.getByRole("button", { name: /В парк/ }).click();
  await expect(card.getByRole("button", { name: /В парк/ })).toHaveAttribute("aria-pressed", "true");
  await expect(card).toContainText("1 голос");
  await expect(card.getByRole("list")).toHaveCount(0);
  expect(mockApi.requests.find((request) => request.path === `/chats/${chatId}/polls`)?.body).toMatchObject({ is_anonymous: true, allow_retract: true, is_quiz: false, correct_option_index: null });
  await page.reload();
  await expect(card).toContainText("1 голос");
  await expect(card.getByRole("button", { name: "Отменить голос" })).toHaveCount(0);
  await card.getByRole("heading").click({ button: "right" });
  const actions = page.getByRole("dialog", { name: "Действия с сообщением" });
  await expect(actions.getByRole("button", { name: "Закрепить", exact: true })).toBeVisible();
  await actions.getByRole("button", { name: "Отменить голос", exact: true }).click();
  await expect(actions).toBeHidden();
  await expect(card).toContainText("0 голосов");
  await expect(card.getByRole("button", { name: /В парк/ })).toHaveAttribute("aria-pressed", "false");
  await page.locator(".msg--poll").getByRole("button", { name: "Действия с сообщением" }).click();
  await expect(actions.getByRole("button", { name: "Отменить голос" })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(actions).toBeHidden();
});

test("public irreversible quiz identifies wrong and correct answers and shows voters", async ({ page, mockApi }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await mockApi.openChat();
  await page.getByRole("button", { name: "Создать опрос", exact: true }).click();
  await page.getByRole("button", { name: "Викторина", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "Новая викторина" });
  await modal.getByLabel("Вопрос", { exact: true }).fill("Сколько будет 2 + 2?");
  await modal.getByLabel("Вариант 1", { exact: true }).fill("Четыре");
  await modal.getByLabel("Вариант 2", { exact: true }).fill("Пять");
  await modal.getByRole("radio", { name: "Правильный ответ: вариант 1" }).check();
  await modal.getByRole("switch", { name: "Анонимное голосование" }).uncheck();
  await modal.getByRole("switch", { name: "Разрешить отмену ответа" }).uncheck();
  const bounds = await modal.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390);
  await modal.getByRole("button", { name: "Создать викторину", exact: true }).click();
  const card = page.getByRole("region", { name: "Викторина", exact: true });
  await card.getByRole("button", { name: /Пять/ }).click();
  await expect(card.getByRole("status")).toContainText("Неверно");
  await expect(card.getByRole("button", { name: /Пять/ })).toContainText("Неправильный ответ");
  await expect(card.getByRole("button", { name: /Четыре/ })).toContainText("Правильный ответ");
  await expect(card.getByRole("button", { name: /Пять/ })).toBeDisabled();
  await expect(card.getByRole("button", { name: /Четыре/ })).toBeDisabled();
  await card.getByRole("heading").click({ button: "right" });
  const actions = page.getByRole("dialog", { name: "Действия с сообщением" });
  await expect(actions).toBeVisible();
  await expect(actions.getByRole("button", { name: "Отменить голос" })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(card.getByRole("list", { name: "Проголосовали за Пять" })).toContainText(`@${user.tag}`);
  await page.reload();
  await expect(card.getByRole("status")).toContainText("Неверно");
});
